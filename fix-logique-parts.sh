#!/bin/bash

# ============================================================
# سكربت تصحيح أجزاء المنطق
# إزالة التكرار وإصلاح الأخطاء
# ============================================================

echo "🔄 بدء تصحيح أجزاء المنطق..."

cd /storage/emulated/0/Web/content/math/lessons/logique

# ============================================================
# دالة تصحيح ملف part
# ============================================================
fix_part() {
    local file=$1
    
    echo "📝 تصحيح $file..."
    
    # ====== 1. إزالة جميع البادجات (badges) ======
    sed -i '/<span class="badge-part"/d' "$file"
    sed -i '/1 Bac Sc/d' "$file"
    sed -i '/Chapitre/d' "$file"
    
    # ====== 2. إزالة السطر الذي يحتوي على البادجات ======
    sed -i '/<p style="text-align:center; color:var(--text-muted); font-size:13px; margin-bottom:16px;">/,/<\/p>/d' "$file"
    
    # ====== 3. إزالة الأزرار المكررة في الأسفل ======
    # حذف جميع أقسام nav-buttons
    sed -i '/<div class="nav-buttons">/,/<\/div>/d' "$file"
    
    # ====== 4. إزالة الأزرار العلوية الزائدة ======
    # حذف الأزرار التي تأتي مباشرة بعد div style
    sed -i '/<a href="index.html" class="back-btn" style="margin-bottom:0;">/,/<\/a>/d' "$file"
    sed -i '/<a href="part[0-9]\.html" class="next-btn">/,/<\/a>/d' "$file"
    
    # ====== 5. إزالة علامات </div> الزائدة ======
    sed -i '/<\/div>$/d' "$file"
    
    echo "✅ تم تصحيح $file"
}

# ============================================================
# تصحيح جميع الأجزاء
# ============================================================

fix_part "part1.html"
fix_part "part2.html"
fix_part "part3.html"
fix_part "part4.html"
fix_part "part5.html"

# ============================================================
# تنظيف الأسطر الفارغة المزدوجة
# ============================================================
echo "🧹 تنظيف الأسطر الفارغة..."

for file in part1.html part2.html part3.html part4.html part5.html; do
    sed -i '/^[[:space:]]*$/d' "$file"
done

# ============================================================
# عرض النتيجة
# ============================================================
echo ""
echo "=================================================="
echo "✅ تم تصحيح جميع الأجزاء بنجاح!"
echo ""
echo "📋 التعديلات المطبقة:"
echo "   ✅ إزالة جميع البادجات"
echo "   ✅ إزالة الأزرار المكررة"
echo "   ✅ إزالة الأزرار العلوية الزائدة"
echo "   ✅ إزالة علامات </div> الزائدة"
echo "=================================================="

